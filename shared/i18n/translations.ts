export type TranslationParams = Record<string, string | number>;

const getNested = (obj: unknown, path: string): unknown =>
  path.split('.').reduce<unknown>((acc, key) => {
    if (acc && typeof acc === 'object' && key in (acc as Record<string, unknown>)) {
      return (acc as Record<string, unknown>)[key];
    }
    return undefined;
  }, obj);

export const interpolate = (text: string, params?: TranslationParams): string => {
  if (!params) return text;
  return Object.keys(params).reduce(
    (acc, key) => acc.replaceAll(`{{${key}}}`, String(params[key])),
    text,
  );
};

export const localeFor = (language: LanguageCode): string => {
  if (language === 'es') return 'es-ES';
  if (language === 'ar') return 'ar';
  if (language === 'fr') return 'fr-FR';
  return 'en-US';
};

export const translate = (
  language: LanguageCode,
  key: string,
  params?: TranslationParams,
): string => {
  const value =
    getNested(translations[language], key) ?? getNested(translations.en, key) ?? key;
  if (typeof value !== 'string') return key;
  return interpolate(value, params);
};
